/**
 * Installs the working tree into OpenCode's plugin directories.
 *
 * A plugin published to npm is loaded as a package and resolves its own
 * imports. A plugin under development is discovered as loose files instead,
 * and OpenCode imports each entry through its path with a cache-busting query
 * — which stops the runtime from resolving a symlink to its real location, so
 * a linked entry cannot find its own `./lib/*` modules. Copying sidesteps that
 * entirely and matches how the published package behaves.
 *
 * The copies are build output: `npm run dev` refreshes them on save, and every
 * copied file carries a header saying so. Edit the repository, never the copy.
 */
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { homedir } from "node:os"
import path from "node:path"
import process from "node:process"

const NAME = "messaging"
const repo = path.resolve(import.meta.dirname, "..")
const config = process.env.OPENCODE_CONFIG ?? path.join(homedir(), ".config", "opencode")
const plugins = path.join(config, "plugins")

const BANNER = `// Generated by @jmfirth/opencode-messaging \`npm run dev\` — do not edit.\n// Source: ${repo}\n`

const targets = {
  server: path.join(plugins, `${NAME}.ts`),
  serverLib: path.join(plugins, "lib"),
  tui: path.join(plugins, "tui", `${NAME}.tsx`),
  tuiLib: path.join(plugins, "tui", "lib"),
}

export async function remove() {
  await Promise.all(Object.values(targets).map((target) => rm(target, { force: true, recursive: true })))
}

async function copyEntry(from: string, to: string) {
  await mkdir(path.dirname(to), { recursive: true })
  await writeFile(to, BANNER + (await readFile(from, "utf8")))
}

// lib/ is copied verbatim beside each entry so `./lib/*` resolves the same way
// it does inside the repository.
async function copyLib(to: string) {
  await rm(to, { force: true, recursive: true })
  await cp(path.join(repo, "src", "lib"), to, { recursive: true })
  for (const file of await readdir(to)) {
    const target = path.join(to, file)
    await writeFile(target, BANNER + (await readFile(target, "utf8")))
  }
}

export async function sync() {
  await copyEntry(path.join(repo, "src", "index.ts"), targets.server)
  await copyEntry(path.join(repo, "src", "tui.tsx"), targets.tui)
  await copyLib(targets.serverLib)
  await copyLib(targets.tuiLib)
}

if (import.meta.filename === process.argv[1]) {
  if (process.argv.includes("--remove")) {
    await remove()
    console.log(`removed ${NAME} from ${plugins}`)
  } else {
    await sync()
    console.log(`installed ${NAME} into ${plugins}`)
  }
}
