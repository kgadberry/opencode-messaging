import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { transformAsync } from "@babel/core"
import typescript from "@babel/preset-typescript"
import solid from "babel-preset-solid"
import { format, resolveConfig } from "prettier"

const source = new URL("../src/tui.tsx", import.meta.url)
const target = new URL("../src/tui.js", import.meta.url)
const result = await transformAsync(await readFile(source, "utf8"), {
  filename: fileURLToPath(source),
  configFile: false,
  babelrc: false,
  presets: [[solid, { moduleName: "@opentui/solid", generate: "universal" }], typescript],
})
if (!result?.code) throw new Error("TUI compilation produced no JavaScript")
const code = await format(`// Generated by npm run compile:tui; edit tui.tsx instead.\n${result.code}`, {
  ...(await resolveConfig(fileURLToPath(source))),
  parser: "babel",
})

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "")
  if (current !== code)
    throw new Error("Compiled TUI is stale; run npm run compile:tui and commit src/tui.js")
  console.log("Compiled TUI is up to date")
} else {
  await writeFile(target, code)
  console.log("Compiled src/tui.js")
}
